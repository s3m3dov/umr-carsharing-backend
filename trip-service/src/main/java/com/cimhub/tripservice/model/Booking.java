package com.cimhub.tripservice.model;

import com.cimhub.common.models.Points;
import jakarta.validation.constraints.Min;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;

/**
 * Booking entity - represents a passenger's seat reservation on a trip
 * Consolidates the previous Ride and Rider entities into a single, clear
 * concept
 */
@Document(collection = "bookings")
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Data
public class Booking {

    @Id
    private String bookingId; // Auto-generated by MongoDB

    // Passenger information
    private String passengerId; // userId of the passenger

    // Trip information
    private String tripId;
    private String driverId;
    private String vehicleNumber;

    // Location details
    private Points pickupLocation;
    private Points dropoffLocation;

    // Booking details
    @Min(1)
    private int requestedSeats;
    private BookingStatus status;

    // Timing (stored in UTC for consistency)
    private Instant rideStartTimeUTC;
    private String rideTimezone; // Original timezone

    // Pricing
    private double estimatedPrice;
    private double pricePerKm;

    // Metadata
    private Instant createdAt;
    private Instant updatedAt;
}
